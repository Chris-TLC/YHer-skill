def _format_contract_block(payload: Mapping[str, object]) -> str:
    return (
        f"{_BEGIN_RESULTS}\n\n```json\n"
        + json.dumps(payload, ensure_ascii=False, sort_keys=True, indent=2)
        + f"\n```\n\n{_END_RESULTS}\n"
    )


def replace_results_contract(
    contract_path: Path | str,
    generated_block: str,
) -> None:
    path = Path(contract_path)
    original = path.read_text(encoding="utf-8")
    if original.count(_BEGIN_RESULTS) != 1 or original.count(_END_RESULTS) != 1:
        raise DatasetContractError(
            "results contract must contain exactly one generated-results marker pair"
        )
    if (
        generated_block.count(_BEGIN_RESULTS) != 1
        or generated_block.count(_END_RESULTS) != 1
    ):
        raise DatasetContractError(
            "generated results block must contain exactly one marker pair"
        )
    start = original.index(_BEGIN_RESULTS)
    end = original.index(_END_RESULTS, start) + len(_END_RESULTS)
    replacement = generated_block.rstrip("\n")
    updated = original[:start] + replacement + original[end:]
    if updated == original:
        return
    temporary = path.with_name(f".{path.name}.s3-tmp")
    temporary.write_text(updated, encoding="utf-8", newline="\n")
    temporary.replace(path)
