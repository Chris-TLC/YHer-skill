def _median_time_metric(
    metric_id: str,
    rows: Sequence[AnalysisRow],
    *,
    raw_hash: str,
) -> MetricValue:
    rows = tuple(row for row in rows if row.valid)
    if not rows:
        raise DatasetContractError(f"metric {metric_id} has no rows")
    times = [float(time_or_budget_plus_one(row)) for row in rows]
    by_target: dict[str, list[float]] = {}
    for row in rows:
        by_target.setdefault(row.target, []).append(
            float(time_or_budget_plus_one(row))
        )
    weighted = sorted(
        (
            time,
            1.0 / (len(by_target) * len(target_times)),
        )
        for target_times in by_target.values()
        for time in target_times
    )
    cumulative = 0.0
    median_low = weighted[-1][0]
    median_high = weighted[-1][0]
    for index, (time, weight) in enumerate(weighted):
        cumulative += weight
        if cumulative >= 0.5 - 1e-12:
            median_low = time
            median_high = (
                weighted[index + 1][0]
                if math.isclose(cumulative, 0.5, abs_tol=1e-12)
                and index + 1 < len(weighted)
                else time
            )
            break
    return MetricValue(
        metric_id=metric_id,
        value=(median_low + median_high) / 2.0,
        numerator=sum(times),
        denominator=len(times),
        weighting="equal_target_then_weighted_median; NC=budget+1",
        n_target=len(by_target),
        n_pair=len(times),
        raw_hash=raw_hash,
    )


