def _plot_confusion(
    rows: Sequence[Mapping[str, object]], *, decision: bool
):
    truths = ("M", "P", "C", "U")
    columns = ("M", "P", "C", "U", "NC") if decision else truths
    figure, axes = plt.subplots(
        1, 3,
        figsize=(10.2 if decision else 9.4, 4.0),
        layout="constrained",
    )
    image = None
    for axis, arm in zip(axes, ("A", "B", "C"), strict=True):
        selected = [
            row
            for row in rows
            if row["arm"] == arm
            and row["condition"] == "matched"
            and int(row["budget"]) == 15
        ]
        lookup = {
            (str(row["truth"]), str(row["decision"])): row for row in selected
        }
        matrix = [
            [float(lookup[(truth, column)]["value"]) for column in columns]
            for truth in truths
        ]
        image = axis.imshow(matrix, cmap="Blues", vmin=0.0, vmax=1.0, aspect="equal")
        axis.set_title(f"Arm {arm}")
        axis.set_xticks(range(len(columns)), columns)
        axis.set_yticks(range(len(truths)), truths)
        axis.set_xlabel(
            "Decision (NC = not converged)" if decision else "Predicted terminal state"
        )
        for row_index, truth in enumerate(truths):
            for column_index, column in enumerate(columns):
                cell = lookup[(truth, column)]
                value = float(cell["value"])
                color = "white" if value >= 0.55 else "black"
                axis.text(
                    column_index,
                    row_index,
                    f"{100.0 * value:.1f}%\n"
                    f"[{100.0 * float(cell['ci_low']):.1f}, "
                    f"{100.0 * float(cell['ci_high']):.1f}]\n"
                    f"(n={int(cell['count'])})",
                    ha="center",
                    va="center",
                    color=color,
                    fontsize=6,
                )
    axes[0].set_ylabel("Truth state")
    if image is not None:
        colorbar = figure.colorbar(image, ax=axes, shrink=0.82, pad=0.02)
        colorbar.set_label("Row share (%)")
        colorbar.ax.yaxis.set_major_formatter(PercentFormatter(xmax=1.0))
    figure.suptitle(
        "Four-state terminal confusion (all valid terminal outputs)"
        if not decision
        else "Four-state decisions with non-convergence (all journeys)"
    )
    total = sum(
        int(row["count"])
        for row in rows
        if row["arm"] == "A"
        and row["condition"] == "matched"
        and int(row["budget"]) == 15
    )
    _add_figure_footer(
        figure,
        f"Cells show target-equal row percentage, 95% CI, and raw count; "
        f"n = {total:,} journeys in Arm A.",
        bottom=0.14,
    )
    return figure


