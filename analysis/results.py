def _results_fragment(
    bundle: ResultBundle, registry: Mapping[str, Mapping[str, object]]
) -> str:
    lines = [
        "# Generated Confirmatory Results",
        "",
        "This fragment is generated from `metric_registry.json`; no result is hand-entered.",
        "",
    ]
    for hypothesis in ("H1", "H2", "H3", "H4", "H5"):
        lines.append(f"## {hypothesis}: {bundle.decisions[hypothesis]}")
        lines.append("")
        evidence = bundle.hypothesis_evidence[hypothesis]
        if not evidence:
            lines.append("Pending validated input; no numeric claim generated.")
        else:
            for metric_id in evidence:
                row = registry[metric_id]
                interval = (
                    f", 95% CI [{float(row['ci_low']):.6f}, "
                    f"{float(row['ci_high']):.6f}]"
                    if row["ci_low"] is not None
                    else ""
                )
                lines.append(
                    f"- `{metric_id}` = {float(row['value']):.6f}{interval}; "
                    f"numerator={float(row['numerator']):.6f}, "
                    f"denominator={int(row['denominator'])}."
                )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


