def expected_programmatic_registry_ids(
    common_support_counts: Mapping[int, int],
) -> frozenset[str]:
    """Return the exact registry ID set generated by the frozen analysis loops."""

    counts = {int(budget): int(count) for budget, count in common_support_counts.items()}
    if set(counts) != {9, 15, 25} or any(count < 0 for count in counts.values()):
        raise DatasetContractError("common-support registry counts are invalid")
    conditions = ("matched", "misspecified")
    budgets = (9, 15, 25)
    arms = ("A", "B", "C")
    ids: set[str] = set()
    for condition in conditions:
        for budget in budgets:
            for arm in arms:
                ids.add(f"p_rescue.full.{condition}.b{budget}.arm_{arm}")
                ids.add(f"c_misdiagnosis.full.{condition}.b{budget}.arm_{arm}")
                for truth_scope in ("ALL", "M", "P", "C", "U"):
                    for outcome in (
                        "correct_convergence",
                        "misdiagnosis",
                        "terminal_accuracy",
                        "convergence",
                    ):
                        ids.add(
                            f"outcome_by_view.{condition}.b{budget}.arm_{arm}."
                            f"truth_{truth_scope}.{outcome}"
                        )
                for field in (
                    "actual_administered_count",
                    "unique_item_count",
                    "unique_family_count",
                    "exact_item_repeat_fraction",
                    "family_repeat_fraction",
                ):
                    ids.add(f"journey_quality.{condition}.b{budget}.arm_{arm}.{field}")
                ids.add(f"held_out_brier.{condition}.b{budget}.arm_{arm}")
                for time_value in range(1, budget + 2):
                    token = str(time_value) if time_value <= budget else f"NC{budget + 1}"
                    ids.add(
                        f"convergence_time.{condition}.b{budget}.arm_{arm}.items_{token}"
                    )
                for truth in ("M", "P", "C", "U"):
                    for decision in ("M", "P", "C", "U"):
                        ids.add(
                            f"confusion.terminal.{condition}.b{budget}.arm_{arm}."
                            f"{truth}.{decision}"
                        )
                    for decision in ("M", "P", "C", "U", "NC"):
                        ids.add(
                            f"confusion.decision.{condition}.b{budget}.arm_{arm}."
                            f"{truth}.{decision}"
                        )
                for denominator in (
                    "all_journeys",
                    "all_converged_journeys",
                    "truth_M_or_U_all_journeys",
                ):
                    ids.add(f"severe.{condition}.b{budget}.arm_{arm}.{denominator}")

    ids.update(
        {
            "h1.primary.matched.b15.rescue_A_minus_B",
            "h2.primary.matched.b9.harm_C_minus_A",
            "h2.primary.matched.b9.no_harm_A_minus_B",
            "h3.matched.b15.terminal_accuracy_A_minus_B",
            "h3.matched.b15.time_to_confidence.arm_A",
            "h3.matched.b15.time_to_confidence.arm_B",
            "h4.misspecified.b15.rescue_A_minus_B",
            "h4.misspecified.b9.harm_C_minus_A",
            "h4.misspecified.b9.no_harm_A_minus_B",
            "h4.degradation.h1_rescue.matched_minus_misspecified",
            "h4.degradation.h2_harm.matched_minus_misspecified",
            "h4.degradation.h2_no_harm.matched_minus_misspecified",
        }
    )
    if counts[15] > 0:
        for condition in conditions:
            ids.update(
                {
                    f"h1.no_repeat.{condition}.b15.arm_A",
                    f"h1.no_repeat.{condition}.b15.arm_B",
                    f"h1.no_repeat.{condition}.b15.rescue_A_minus_B",
                }
            )
    if counts[9] > 0:
        for condition in conditions:
            ids.update(
                {
                    f"h2.no_repeat.{condition}.b9.arm_A",
                    f"h2.no_repeat.{condition}.b9.arm_B",
                    f"h2.no_repeat.{condition}.b9.arm_C",
                    f"h2.no_repeat.{condition}.b9.harm_C_minus_A",
                    f"h2.no_repeat.{condition}.b9.no_harm_A_minus_B",
                }
            )
    for item_type in ("mcq", "numeric"):
        for measure in (
            "generator_probability",
            "production_probability",
            "generator_minus_production",
        ):
            ids.add(f"misspecification.item_type.{item_type}.{measure}")
    for truth in ("P", "C"):
        for budget in budgets:
            for arm in arms:
                prefix = (
                    f"exploratory_posthoc.prerequisite.truth_{truth}.matched."
                    f"b{budget}.arm_{arm}."
                )
                ids.update(
                    prefix + suffix
                    for suffix in (
                        "prerequisite_count",
                        "prerequisite_share",
                        "direct_count",
                        "terminal_accuracy",
                        "correct_convergence",
                        "terminal_minus_correct_convergence",
                    )
                )
    for budget, count in counts.items():
        if count > 0:
            ids.add(f"no_repeat.b{budget}.target_fraction")
    return frozenset(ids)


@dataclass(frozen=True)
class ResultBundle:
    raw_hash: str
    registry: MetricRegistry
    decisions: dict[str, str | None]
    no_repeat_sets: Mapping[int, NoRepeatSet]
    bootstrap_iterations: int
    figure_rows: Mapping[str, tuple[dict[str, object], ...]]
    table_rows: Mapping[str, tuple[dict[str, object], ...]]
    hypothesis_evidence: Mapping[str, tuple[str, ...]]
    canonical_rows: tuple[AnalysisRow, ...]
    validation: Mapping[str, object]
    conditional_metric_audit: Mapping[str, Mapping[str, object]]
    static_audit_policy: Mapping[str, str]
    source_provenance: Mapping[str, str]
    analysis_provenance: Mapping[str, object]


def build_results(
    rows: Iterable[AnalysisRow],
    *,
    events: Iterable[AnalysisEvent],
    raw_hash: str,
    no_repeat_sets: Mapping[int, NoRepeatSet],
    bootstrap_iterations: int = 10_000,
    source_provenance: Mapping[str, str],
    analysis_provenance: Mapping[str, object],
    schema_invalid_count: int = 0,
    schema_invalid_reasons: Mapping[str, int] | None = None,
    intended_journey_count: int | None = None,
) -> ResultBundle:
    values = tuple(rows)
    event_values = tuple(events)
    if not values:
        raise DatasetContractError("analysis has no canonical rows")
    if not event_values:
        raise DatasetContractError("analysis has no canonical events")
    invalid_reasons = dict(schema_invalid_reasons or {})
    if (
        schema_invalid_count < 0
        or any(
            not isinstance(reason, str)
            or not reason
            or not isinstance(count, int)
            or count <= 0
            for reason, count in invalid_reasons.items()
        )
        or sum(invalid_reasons.values()) != schema_invalid_count
    ):
        raise DatasetContractError("schema-invalid quarantine accounting is inconsistent")
    registry = MetricRegistry(raw_hash=raw_hash)
    eligible_targets = frozenset(row.target for row in values if row.h1_h2_eligible)
    all_targets = frozenset(row.target for row in values)
    if not eligible_targets:
        raise DatasetContractError("H1/H2 eligible target set is empty")
    for budget, support in no_repeat_sets.items():
        outside_eligible = set(support.targets) - eligible_targets
        if outside_eligible:
            raise DatasetContractError(
                f"no-repeat target set at budget {budget} contains non-eligible targets: "
                + ", ".join(sorted(outside_eligible))
            )
    provenance = _validate_source_provenance(source_provenance)
    code_provenance = _validate_analysis_provenance(analysis_provenance)
    bootstrap_distributions: dict[str, tuple[float, ...]] = {}
    conditional_metric_audit: dict[str, Mapping[str, object]] = {}
    static_policy = _load_static_audit_policy()

    def selected(
        *,
        truth: str | None = None,
        condition: str | None = None,
        arm: str | None = None,
        budget: int | None = None,
        targets: frozenset[str] | None = None,
    ) -> tuple[AnalysisRow, ...]:
        return tuple(
            row
            for row in values
            if (truth is None or row.truth == truth)
            and (condition is None or row.condition == condition)
            and (arm is None or row.arm == arm)
            and (budget is None or row.budget == budget)
            and (targets is None or row.target in targets)
        )

    def rate_with_ci(
        metric_id: str,
        metric_rows: Sequence[AnalysisRow],
        outcome: str,
    ) -> MetricValue:
        point = rate_metric(
            metric_id,
            metric_rows,
            outcome=outcome,  # type: ignore[arg-type]
            raw_hash=raw_hash,
        )
        distribution = bootstrap_rate_distribution(
            metric_rows,
            outcome=outcome,  # type: ignore[arg-type]
            iterations=bootstrap_iterations,
            seed=BOOTSTRAP_SEED,
        )
        low, high = percentile_interval(distribution)
        metric = replace(point, ci_low=low, ci_high=high)
        registry.add(metric)
        bootstrap_distributions[metric_id] = distribution
        return metric

    def contrast_with_ci(
        metric_id: str,
        metric_rows: Sequence[AnalysisRow],
        *,
        left: str,
        right: str,
        outcome: str,
    ) -> MetricValue:
        point = contrast_metric(
            metric_id,
            metric_rows,
            left_arm=left,
            right_arm=right,
            outcome=outcome,  # type: ignore[arg-type]
            raw_hash=raw_hash,
        )
        distribution = bootstrap_contrast_distribution(
            metric_rows,
            left_arm=left,
            right_arm=right,
            outcome=outcome,  # type: ignore[arg-type]
            iterations=bootstrap_iterations,
            seed=BOOTSTRAP_SEED,
        )
        low, high = percentile_interval(distribution)
        metric = replace(point, ci_low=low, ci_high=high)
        registry.add(metric)
        bootstrap_distributions[metric_id] = distribution
        return metric

    def ratio_with_ci(
        metric_id: str,
        metric_rows: Sequence[AnalysisRow],
        *,
        numerator,
        denominator,
        weighting: str,
    ) -> MetricValue:
        point_audit: dict[str, object] = {}
        point = _target_ratio_metric(
            metric_id,
            metric_rows,
            numerator=numerator,
            denominator=denominator,
            raw_hash=raw_hash,
            weighting=weighting,
            audit=point_audit,
        )
        bootstrap_audit: dict[str, object] = {}
        distribution = bootstrap_ratio_distribution(
            metric_rows,
            numerator=numerator,
            denominator=denominator,
            iterations=bootstrap_iterations,
            seed=BOOTSTRAP_SEED,
            audit=bootstrap_audit,
        )
        low, high = percentile_interval(distribution)
        audit = {**point_audit, **bootstrap_audit}
        conditional_metric_audit[metric_id] = audit
        metric = replace(
            point,
            ci_low=low,
            ci_high=high,
            weighting=(
                f"{weighting}; zero_denominator_policy=record_NA_no_redraw; "
                f"bootstrap_attempted_iterations={audit['attempted_iterations']}; "
                f"bootstrap_defined_iterations={audit['defined_iterations']}"
            ),
        )
        registry.add(metric)
        bootstrap_distributions[metric_id] = distribution
        return metric

    def mean_with_ci(
        metric_id: str,
        metric_rows: Sequence[AnalysisRow],
        field: str,
    ) -> MetricValue:
        point = _mean_metric(metric_id, metric_rows, field=field, raw_hash=raw_hash)
        distribution = bootstrap_mean_distribution(
            metric_rows,
            field=field,  # type: ignore[arg-type]
            iterations=bootstrap_iterations,
            seed=BOOTSTRAP_SEED,
        )
        low, high = percentile_interval(distribution)
        metric = replace(point, ci_low=low, ci_high=high)
        registry.add(metric)
        bootstrap_distributions[metric_id] = distribution
        return metric

    def median_time_with_ci(
        metric_id: str,
        metric_rows: Sequence[AnalysisRow],
    ) -> MetricValue:
        point = _median_time_metric(metric_id, metric_rows, raw_hash=raw_hash)
        distribution = bootstrap_median_time_distribution(
            metric_rows,
            iterations=bootstrap_iterations,
            seed=BOOTSTRAP_SEED,
        )
        low, high = percentile_interval(distribution)
        metric = replace(point, ci_low=low, ci_high=high)
        registry.add(metric)
        bootstrap_distributions[metric_id] = distribution
        return metric

    p_rows: list[dict[str, object]] = []
    c_rows: list[dict[str, object]] = []
    for condition in ("matched", "misspecified"):
        for budget in (9, 15, 25):
            for arm in ("A", "B", "C"):
                metric = rate_with_ci(
                    f"p_rescue.full.{condition}.b{budget}.arm_{arm}",
                    selected(
                        truth="P",
                        condition=condition,
                        arm=arm,
                        budget=budget,
                        targets=eligible_targets,
                    ),
                    "correct_convergence",
                )
                p_rows.append(_figure_metric_row(metric, condition, arm, budget, "full"))
                metric = rate_with_ci(
                    f"c_misdiagnosis.full.{condition}.b{budget}.arm_{arm}",
                    selected(
                        truth="C",
                        condition=condition,
                        arm=arm,
                        budget=budget,
                        targets=eligible_targets,
                    ),
                    "misdiagnosis",
                )
                c_rows.append(_figure_metric_row(metric, condition, arm, budget, "full"))

    outcome_rows: list[dict[str, object]] = []
    for condition in ("matched", "misspecified"):
        for budget in (9, 15, 25):
            for arm in ("A", "B", "C"):
                arm_rows = selected(
                    condition=condition,
                    arm=arm,
                    budget=budget,
                    targets=all_targets,
                )
                for truth_scope in ("ALL", "M", "P", "C", "U"):
                    metric_rows = tuple(
                        row
                        for row in arm_rows
                        if truth_scope == "ALL" or row.truth == truth_scope
                    )
                    for outcome in (
                        "correct_convergence",
                        "misdiagnosis",
                        "terminal_accuracy",
                        "convergence",
                    ):
                        metric = rate_with_ci(
                            f"outcome_by_view.{condition}.b{budget}.arm_{arm}."
                            f"truth_{truth_scope}.{outcome}",
                            metric_rows,
                            outcome,
                        )
                        outcome_rows.append(
                            {
                                "metric_id": metric.metric_id,
                                "condition": condition,
                                "budget": budget,
                                "arm": arm,
                                "truth_scope": truth_scope,
                                "outcome": outcome,
                                "value": metric.value,
                                "ci_low": metric.ci_low,
                                "ci_high": metric.ci_high,
                                "numerator": metric.numerator,
                                "denominator": metric.denominator,
                                "n_target": metric.n_target,
                                "n_pair": metric.n_pair,
                            }
                        )

    journey_quality_rows: list[dict[str, object]] = []
    for condition in ("matched", "misspecified"):
        for budget in (9, 15, 25):
            for arm in ("A", "B", "C"):
                metric_rows = selected(
                    condition=condition,
                    arm=arm,
                    budget=budget,
                    targets=all_targets,
                )
                for field in (
                    "actual_administered_count",
                    "unique_item_count",
                    "unique_family_count",
                    "exact_item_repeat_fraction",
                    "family_repeat_fraction",
                ):
                    metric = mean_with_ci(
                        f"journey_quality.{condition}.b{budget}.arm_{arm}.{field}",
                        metric_rows,
                        field,
                    )
                    journey_quality_rows.append(
                        {
                            "metric_id": metric.metric_id,
                            "condition": condition,
                            "budget": budget,
                            "arm": arm,
                            "measure": field,
                            "value": metric.value,
                            "ci_low": metric.ci_low,
                            "ci_high": metric.ci_high,
                            "numerator": metric.numerator,
                            "denominator": metric.denominator,
                            "n_target": metric.n_target,
                            "n_pair": metric.n_pair,
                        }
                    )

    h1_a = _lookup(registry, "p_rescue.full.matched.b15.arm_A")
    h1_rescue = contrast_with_ci(
        "h1.primary.matched.b15.rescue_A_minus_B",
        selected(
            truth="P",
            condition="matched",
            budget=15,
            targets=eligible_targets,
        ),
        left="A",
        right="B",
        outcome="correct_convergence",
    )
    h2_harm = contrast_with_ci(
        "h2.primary.matched.b9.harm_C_minus_A",
        selected(
            truth="C",
            condition="matched",
            budget=9,
            targets=eligible_targets,
        ),
        left="C",
        right="A",
        outcome="misdiagnosis",
    )
    h2_no_harm = contrast_with_ci(
        "h2.primary.matched.b9.no_harm_A_minus_B",
        selected(
            truth="C",
            condition="matched",
            budget=9,
            targets=eligible_targets,
        ),
        left="A",
        right="B",
        outcome="misdiagnosis",
    )

    for hypothesis, truth, budget, outcome, arms in (
        ("h1", "P", 15, "correct_convergence", ("A", "B")),
        ("h2", "C", 9, "misdiagnosis", ("A", "B", "C")),
    ):
        support = frozenset(no_repeat_sets[budget].targets) & eligible_targets
        if not support:
            continue
        for condition in ("matched", "misspecified"):
            for arm in arms:
                rate_with_ci(
                    f"{hypothesis}.no_repeat.{condition}.b{budget}.arm_{arm}",
                    selected(
                        truth=truth,
                        condition=condition,
                        arm=arm,
                        budget=budget,
                        targets=support,
                    ),
                    outcome,
                )
            if hypothesis == "h1":
                contrast_with_ci(
                    f"h1.no_repeat.{condition}.b15.rescue_A_minus_B",
                    selected(
                        truth="P",
                        condition=condition,
                        budget=15,
                        targets=support,
                    ),
                    left="A",
                    right="B",
                    outcome="correct_convergence",
                )
            else:
                contrast_with_ci(
                    f"h2.no_repeat.{condition}.b9.harm_C_minus_A",
                    selected(
                        truth="C",
                        condition=condition,
                        budget=9,
                        targets=support,
                    ),
                    left="C",
                    right="A",
                    outcome="misdiagnosis",
                )
                contrast_with_ci(
                    f"h2.no_repeat.{condition}.b9.no_harm_A_minus_B",
                    selected(
                        truth="C",
                        condition=condition,
                        budget=9,
                        targets=support,
                    ),
                    left="A",
                    right="B",
                    outcome="misdiagnosis",
                )

    h3_rows = selected(condition="matched", budget=15, targets=all_targets)
    h3_accuracy = contrast_with_ci(
        "h3.matched.b15.terminal_accuracy_A_minus_B",
        h3_rows,
        left="A",
        right="B",
        outcome="terminal_accuracy",
    )
    h3_median_a = median_time_with_ci(
        "h3.matched.b15.time_to_confidence.arm_A",
        tuple(row for row in h3_rows if row.arm == "A"),
    )
    h3_median_b = median_time_with_ci(
        "h3.matched.b15.time_to_confidence.arm_B",
        tuple(row for row in h3_rows if row.arm == "B"),
    )

    h4_rescue = contrast_with_ci(
        "h4.misspecified.b15.rescue_A_minus_B",
        selected(
            truth="P",
            condition="misspecified",
            budget=15,
            targets=eligible_targets,
        ),
        left="A",
        right="B",
        outcome="correct_convergence",
    )
    h4_harm = contrast_with_ci(
        "h4.misspecified.b9.harm_C_minus_A",
        selected(
            truth="C",
            condition="misspecified",
            budget=9,
            targets=eligible_targets,
        ),
        left="C",
        right="A",
        outcome="misdiagnosis",
    )
    h4_no_harm = contrast_with_ci(
        "h4.misspecified.b9.no_harm_A_minus_B",
        selected(
            truth="C",
            condition="misspecified",
            budget=9,
            targets=eligible_targets,
        ),
        left="A",
        right="B",
        outcome="misdiagnosis",
    )
    h4_h1_degradation = _degradation_metric(
        "h4.degradation.h1_rescue.matched_minus_misspecified",
        matched=h1_rescue,
        misspecified=h4_rescue,
        matched_distribution=bootstrap_distributions[h1_rescue.metric_id],
        misspecified_distribution=bootstrap_distributions[h4_rescue.metric_id],
        raw_hash=raw_hash,
    )
    h4_h2_degradation = _degradation_metric(
        "h4.degradation.h2_harm.matched_minus_misspecified",
        matched=h2_harm,
        misspecified=h4_harm,
        matched_distribution=bootstrap_distributions[h2_harm.metric_id],
        misspecified_distribution=bootstrap_distributions[h4_harm.metric_id],
        raw_hash=raw_hash,
    )
    h4_h2_no_harm_degradation = _degradation_metric(
        "h4.degradation.h2_no_harm.matched_minus_misspecified",
        matched=h2_no_harm,
        misspecified=h4_no_harm,
        matched_distribution=bootstrap_distributions[h2_no_harm.metric_id],
        misspecified_distribution=bootstrap_distributions[h4_no_harm.metric_id],
        raw_hash=raw_hash,
    )
    registry.add(h4_h1_degradation)
    registry.add(h4_h2_degradation)
    registry.add(h4_h2_no_harm_degradation)
    degradation_rows = (
        _effect_figure_row(h1_rescue, "H1 rescue", "matched"),
        _effect_figure_row(h4_rescue, "H1 rescue", "misspecified"),
        _effect_figure_row(h2_harm, "H2 harm", "matched"),
        _effect_figure_row(h4_harm, "H2 harm", "misspecified"),
        _effect_figure_row(h2_no_harm, "H2 no-harm", "matched"),
        _effect_figure_row(h4_no_harm, "H2 no-harm", "misspecified"),
        _effect_figure_row(h4_h1_degradation, "H1 rescue", "degradation"),
        _effect_figure_row(h4_h2_degradation, "H2 harm", "degradation"),
        _effect_figure_row(
            h4_h2_no_harm_degradation, "H2 no-harm", "degradation"
        ),
    )

    misspecification_item_type_rows: list[dict[str, object]] = []
    misspecified_events = tuple(
        event
        for event in event_values
        if event.valid and event.condition == "misspecified"
    )
    for item_type in ("mcq", "numeric"):
        item_events = tuple(
            event for event in misspecified_events if event.item_type == item_type
        )
        if not item_events:
            raise DatasetContractError(
                f"misspecified event table has no {item_type} observations"
            )
        generator_value = lambda event: event.generator_probability
        production_value = lambda event: event.production_probability
        gap_value = lambda event: (
            event.generator_probability - event.production_probability
        )
        generator = _event_mean_metric(
            f"misspecification.item_type.{item_type}.generator_probability",
            item_events,
            value=generator_value,
            distribution=bootstrap_event_mean_distribution(
                item_events,
                value=generator_value,
                iterations=ITEM_TYPE_DIAGNOSTIC_BOOTSTRAP_ITERATIONS,
            ),
            raw_hash=raw_hash,
        )
        production = _event_mean_metric(
            f"misspecification.item_type.{item_type}.production_probability",
            item_events,
            value=production_value,
            distribution=bootstrap_event_mean_distribution(
                item_events,
                value=production_value,
                iterations=ITEM_TYPE_DIAGNOSTIC_BOOTSTRAP_ITERATIONS,
            ),
            raw_hash=raw_hash,
        )
        gap = _event_mean_metric(
            f"misspecification.item_type.{item_type}.generator_minus_production",
            item_events,
            value=gap_value,
            distribution=bootstrap_event_mean_distribution(
                item_events,
                value=gap_value,
                iterations=ITEM_TYPE_DIAGNOSTIC_BOOTSTRAP_ITERATIONS,
            ),
            raw_hash=raw_hash,
        )
        registry.add(generator)
        registry.add(production)
        registry.add(gap)
        misspecification_item_type_rows.append(
            {
                "item_type": item_type,
                "generator_probability": generator.value,
                "generator_ci_low": generator.ci_low,
                "generator_ci_high": generator.ci_high,
                "production_probability": production.value,
                "production_ci_low": production.ci_low,
                "production_ci_high": production.ci_high,
                "generator_minus_production": gap.value,
                "gap_ci_low": gap.ci_low,
                "gap_ci_high": gap.ci_high,
                "event_count": generator.denominator,
                "journey_count": generator.n_pair,
                "n_target": generator.n_target,
                "bootstrap_iterations": ITEM_TYPE_DIAGNOSTIC_BOOTSTRAP_ITERATIONS,
                "bootstrap_unit": (
                    "target_fixed_paired_replicate_whole_journey_event_cluster"
                ),
                "interpretation": (
                    "generator_diagnostic_not_item_type_H1_H2_estimand"
                ),
            }
        )

    brier_rows: list[dict[str, object]] = []
    for condition in ("matched", "misspecified"):
        for budget in (9, 15, 25):
            for arm in ("A", "B", "C"):
                metric = mean_with_ci(
                    f"held_out_brier.{condition}.b{budget}.arm_{arm}",
                    tuple(
                        row
                        for row in selected(
                            condition=condition,
                            arm=arm,
                            budget=budget,
                            targets=all_targets,
                        )
                        if row.held_out_brier is not None
                    ),
                    "held_out_brier",
                )
                brier_rows.append(
                    _figure_metric_row(metric, condition, arm, budget, "full")
                )

    convergence_rows: list[dict[str, object]] = []
    for condition in ("matched", "misspecified"):
        for budget in (9, 15, 25):
            convergence_categories = tuple(range(1, budget + 2))
            for arm in ("A", "B", "C"):
                metric_rows = selected(
                    condition=condition,
                    arm=arm,
                    budget=budget,
                    targets=all_targets,
                )
                distributions = bootstrap_category_rate_distributions(
                    metric_rows,
                    categories=convergence_categories,
                    category=time_or_budget_plus_one,
                    iterations=bootstrap_iterations,
                    seed=BOOTSTRAP_SEED,
                )
                for time_value in convergence_categories:
                    time_token = (
                        str(time_value)
                        if time_value <= budget
                        else f"NC{budget + 1}"
                    )
                    metric_id = (
                        f"convergence_time.{condition}.b{budget}.arm_{arm}."
                        f"items_{time_token}"
                    )
                    point = _predicate_rate_metric(
                        metric_id,
                        metric_rows,
                        predicate=lambda row, expected=time_value: (
                            time_or_budget_plus_one(row) == expected
                        ),
                        raw_hash=raw_hash,
                    )
                    low, high = percentile_interval(distributions[time_value])
                    metric = replace(point, ci_low=low, ci_high=high)
                    registry.add(metric)
                    convergence_rows.append(
                        {
                            "metric_id": metric.metric_id,
                            "condition": condition,
                            "budget": budget,
                            "arm": arm,
                            "time_value": time_value,
                            "time_label": (
                                str(time_value)
                                if time_value <= budget
                                else f"NC ({budget + 1})"
                            ),
                            "value": metric.value,
                            "ci_low": metric.ci_low,
                            "ci_high": metric.ci_high,
                            "n_target": metric.n_target,
                            "n_pair": metric.n_pair,
                        }
                    )

    prerequisite_rows: list[dict[str, object]] = []
    for truth in ("P", "C"):
        for budget in (9, 15, 25):
            for arm in ("A", "B", "C"):
                mechanism_rows = selected(
                    truth=truth,
                    condition="matched",
                    arm=arm,
                    budget=budget,
                    targets=eligible_targets,
                )
                mechanism_metrics: dict[str, MetricValue] = {}
                for field in (
                    "prerequisite_count",
                    "prerequisite_share",
                    "direct_count",
                ):
                    metric = _mean_metric(
                        f"exploratory_posthoc.prerequisite.truth_{truth}.matched."
                        f"b{budget}.arm_{arm}.{field}",
                        mechanism_rows,
                        field=field,
                        raw_hash=raw_hash,
                    )
                    distribution = bootstrap_mean_distribution(
                        mechanism_rows,
                        field=field,  # type: ignore[arg-type]
                        iterations=bootstrap_iterations,
                        seed=BOOTSTRAP_SEED,
                    )
                    low, high = percentile_interval(distribution)
                    metric = replace(
                        metric,
                        weighting=f"exploratory_posthoc; {metric.weighting}",
                        ci_low=low,
                        ci_high=high,
                    )
                    registry.add(metric)
                    mechanism_metrics[field] = metric
                for outcome in ("terminal_accuracy", "correct_convergence"):
                    metric = rate_metric(
                        f"exploratory_posthoc.prerequisite.truth_{truth}.matched."
                        f"b{budget}.arm_{arm}.{outcome}",
                        mechanism_rows,
                        outcome=outcome,  # type: ignore[arg-type]
                        raw_hash=raw_hash,
                    )
                    distribution = bootstrap_rate_distribution(
                        mechanism_rows,
                        outcome=outcome,  # type: ignore[arg-type]
                        iterations=bootstrap_iterations,
                        seed=BOOTSTRAP_SEED,
                    )
                    low, high = percentile_interval(distribution)
                    metric = replace(
                        metric,
                        weighting=f"exploratory_posthoc; {metric.weighting}",
                        ci_low=low,
                        ci_high=high,
                    )
                    registry.add(metric)
                    mechanism_metrics[outcome] = metric
                terminal = mechanism_metrics["terminal_accuracy"]
                correct = mechanism_metrics["correct_convergence"]
                gap_distribution = bootstrap_value_distribution(
                    mechanism_rows,
                    value=lambda row: float(
                        row.valid
                        and row.argmax == row.truth
                        and not row.converged
                    ),
                    iterations=bootstrap_iterations,
                    seed=BOOTSTRAP_SEED,
                )
                gap_low, gap_high = percentile_interval(gap_distribution)
                registry.add(
                    MetricValue(
                        metric_id=(
                            f"exploratory_posthoc.prerequisite.truth_{truth}.matched."
                            f"b{budget}.arm_{arm}.terminal_minus_correct_convergence"
                        ),
                        value=terminal.value - correct.value,
                        numerator=terminal.numerator - correct.numerator,
                        denominator=terminal.denominator,
                        weighting=(
                            "exploratory_posthoc; equal_target_then_replicate paired "
                            "indicator difference"
                        ),
                        n_target=terminal.n_target,
                        n_pair=terminal.n_pair,
                        raw_hash=raw_hash,
                        ci_low=gap_low,
                        ci_high=gap_high,
                    )
                )
                share = mechanism_metrics["prerequisite_share"]
                prerequisite_rows.append(
                    _figure_metric_row(
                        share,
                        "matched",
                        arm,
                        budget,
                        f"exploratory_posthoc_truth_{truth}",
                    )
                )

    confusion_rows: list[dict[str, object]] = []
    decision_confusion_rows: list[dict[str, object]] = []
    state_set = frozenset(("M", "P", "C", "U"))
    for condition in ("matched", "misspecified"):
        for budget in (9, 15, 25):
            for arm in ("A", "B", "C"):
                matrix_rows = selected(
                    condition=condition,
                    arm=arm,
                    budget=budget,
                    targets=all_targets,
                )
                for is_decision, destination in (
                    (False, confusion_rows),
                    (True, decision_confusion_rows),
                ):
                    matrix = confusion_matrix(matrix_rows, decision=is_decision)
                    for truth in matrix.rows:
                        truth_rows = tuple(
                            row for row in matrix_rows if row.truth == truth
                        )
                        for column in matrix.columns:
                            if is_decision:
                                numerator = lambda row, expected=column: (
                                    row.argmax
                                    if row.valid
                                    and row.converged
                                    and row.argmax in state_set
                                    else "NC"
                                ) == expected
                                denominator = lambda row: True
                            else:
                                numerator = lambda row, expected=column: (
                                    row.valid and row.argmax == expected
                                )
                                denominator = lambda row: (
                                    row.valid and row.argmax in state_set
                                )
                            kind = "decision" if is_decision else "terminal"
                            metric_id = (
                                f"confusion.{kind}.{condition}.b{budget}.arm_{arm}."
                                f"{truth}.{column}"
                            )
                            metric = ratio_with_ci(
                                metric_id,
                                truth_rows,
                                numerator=numerator,
                                denominator=denominator,
                                weighting=(
                                    "equal_target_then_replicate_ratio; "
                                    + (
                                        "all_journeys"
                                        if is_decision
                                        else "valid_terminal_outputs"
                                    )
                                ),
                            )
                            destination.append(
                                {
                                    "metric_id": metric.metric_id,
                                    "condition": condition,
                                    "budget": budget,
                                    "arm": arm,
                                    "truth": truth,
                                    "decision": column,
                                    "count": int(metric.numerator),
                                    "row_denominator": metric.denominator,
                                    "value": metric.value,
                                    "ci_low": metric.ci_low,
                                    "ci_high": metric.ci_high,
                                    "n_target": metric.n_target,
                                    "n_pair": metric.n_pair,
                                }
                            )

    for condition in ("matched", "misspecified"):
        for budget in (9, 15, 25):
            for arm in ("A", "B", "C"):
                all_journeys = selected(
                    condition=condition,
                    arm=arm,
                    budget=budget,
                    targets=all_targets,
                )
                severe = lambda row: row.valid and (row.truth, row.argmax) in {
                    ("M", "U"),
                    ("U", "M"),
                }
                severe_specs = {
                    "all_journeys": (severe, lambda row: True),
                    "all_converged_journeys": (
                        lambda row: row.converged and severe(row),
                        lambda row: row.converged,
                    ),
                    "truth_M_or_U_all_journeys": (
                        severe,
                        lambda row: row.truth in {"M", "U"},
                    ),
                }
                for denominator_name, (numerator, denominator) in severe_specs.items():
                    ratio_with_ci(
                        (
                            f"severe.{condition}.b{budget}.arm_{arm}."
                            f"{denominator_name}"
                        ),
                        all_journeys,
                        numerator=numerator,
                        denominator=denominator,
                        weighting=(
                            "equal_target_then_replicate_ratio; "
                            f"{denominator_name}"
                        ),
                    )

    for budget, support in sorted(no_repeat_sets.items()):
        if support.n_target:
            registry.add(
                MetricValue(
                    metric_id=f"no_repeat.b{budget}.target_fraction",
                    value=support.n_target / len(all_targets),
                    numerator=float(support.n_target),
                    denominator=len(all_targets),
                    weighting="fixed_target_set",
                    n_target=len(all_targets),
                    n_pair=len(all_targets),
                    raw_hash=raw_hash,
                )
            )

    decisions = {
        "H1": decide_h1(
            a_rate=h1_a.value,
            rescue_point=h1_rescue.value,
            rescue_ci_low=_required(h1_rescue.ci_low),
        ),
        "H2": decide_h2(
            harm_point=h2_harm.value,
            harm_ci_low=_required(h2_harm.ci_low),
            no_harm_point=h2_no_harm.value,
            no_harm_ci_high=_required(h2_no_harm.ci_high),
        ),
        "H3": decide_h3(
            accuracy_point=h3_accuracy.value,
            accuracy_ci_low=_required(h3_accuracy.ci_low),
            median_a=h3_median_a.value,
            median_b=h3_median_b.value,
        ),
        "H4": decide_h4(
            rescue_point=h4_rescue.value,
            harm_point=h4_harm.value,
        ),
        "H5": None,
    }
    evidence = {
        "H1": (h1_a.metric_id, h1_rescue.metric_id),
        "H2": (h2_harm.metric_id, h2_no_harm.metric_id),
        "H3": (h3_accuracy.metric_id, h3_median_a.metric_id, h3_median_b.metric_id),
        "H4": (
            h4_rescue.metric_id,
            h4_harm.metric_id,
            h4_h1_degradation.metric_id,
            h4_h2_degradation.metric_id,
            h4_no_harm.metric_id,
            h4_h2_no_harm_degradation.metric_id,
            "h1.no_repeat.misspecified.b15.rescue_A_minus_B",
            "h2.no_repeat.misspecified.b9.harm_C_minus_A",
            "h2.no_repeat.misspecified.b9.no_harm_A_minus_B",
            "misspecification.item_type.mcq.generator_minus_production",
            "misspecification.item_type.numeric.generator_minus_production",
        ),
        "H5": (),
    }
    bundle = ResultBundle(
        raw_hash=raw_hash,
        registry=registry,
        decisions=decisions,
        no_repeat_sets=no_repeat_sets,
        bootstrap_iterations=bootstrap_iterations,
        figure_rows={
            "p_rescue": tuple(p_rows),
            "c_misdiagnosis": tuple(c_rows),
            "matched_vs_misspecified": degradation_rows,
            "confusion_terminal": tuple(confusion_rows),
            "confusion_decision": tuple(decision_confusion_rows),
            "held_out_brier": tuple(brier_rows),
            "convergence_distribution": tuple(convergence_rows),
            "prerequisite_share": tuple(prerequisite_rows),
            "misspecification_by_item_type": tuple(
                misspecification_item_type_rows
            ),
        },
        table_rows={
            "outcomes_by_view": tuple(outcome_rows),
            "journey_quality": tuple(journey_quality_rows),
            "misspecification_by_item_type": tuple(
                misspecification_item_type_rows
            ),
        },
        hypothesis_evidence=evidence,
        canonical_rows=values,
        validation={
            "canonical_view_count": len(values),
            "programmatic_journey_count": (
                int(intended_journey_count)
                if intended_journey_count is not None
                else len(values) // 3
            ),
            "intended_journey_count": (
                int(intended_journey_count)
                if intended_journey_count is not None
                else len(values) // 3
            ),
            "target_count": len(all_targets),
            "h1_h2_eligible_target_count": len(eligible_targets),
            "budgets": sorted({row.budget for row in values}),
            "valid_journey_count": sum(
                row.valid for row in values if row.budget == 25
            ),
            "structural_failure_count": sum(
                not row.valid
                and str(row.exclusion_reason or "").startswith("structural_failure")
                for row in values
                if row.budget == 25
            ),
            "schema_invalid_count": schema_invalid_count,
            "schema_invalid_reasons": {
                reason: invalid_reasons[reason] for reason in sorted(invalid_reasons)
            },
            "estimand_excluded_journey_count": sum(
                not row.valid for row in values if row.budget == 25
            ),
            "estimand_excluded_view_count": sum(not row.valid for row in values),
            "estimand_exclusion_reasons": _exclusion_reason_counts(values),
            "estimand_exclusion_arms": _exclusion_arm_counts(values),
            "estimand_exclusion_targets": sorted(
                {
                    row.target
                    for row in values
                    if row.budget == 25 and not row.valid
                }
            ),
        },
        conditional_metric_audit={
            metric_id: conditional_metric_audit[metric_id]
            for metric_id in sorted(conditional_metric_audit)
        },
        static_audit_policy=static_policy,
        source_provenance=provenance,
        analysis_provenance=code_provenance,
    )
    observed_registry_ids = {
        str(record["metric_id"]) for record in bundle.registry.records()
    }
    expected_registry_ids = expected_programmatic_registry_ids(
        {budget: value.n_target for budget, value in no_repeat_sets.items()}
    )
    if observed_registry_ids != expected_registry_ids:
        raise DatasetContractError("generated registry ID set is not canonical")
    clear_bootstrap_weight_cache()
    return bundle


def write_results(bundle: ResultBundle, output_dir: Path | str) -> Path:
    root = Path(output_dir)
    figures = root / "figures"
    tables = root / "tables"
    root.mkdir(parents=True, exist_ok=True)
    figures.mkdir(parents=True, exist_ok=True)
    tables.mkdir(parents=True, exist_ok=True)
    bundle.registry.write(root)
    written = {
        root / "metric_registry.json",
        root / "metric_registry.csv",
    }
    policy_source = Path(__file__).with_name("static_audit_policy.json")
    policy_destination = root / "static_audit_policy.json"
    policy_destination.write_bytes(policy_source.read_bytes())
    written.add(policy_destination)
    registry_by_id = {
        str(row["metric_id"]): row for row in bundle.registry.records()
    }
    results = {
        "raw_hash": bundle.raw_hash,
        "source_run_started_at_utc": bundle.source_provenance[
            "run_started_at_utc"
        ],
        "analysis_code_committed_at_utc": bundle.analysis_provenance[
            "analysis_code_committed_at_utc"
        ],
        "analysis_timestamp_policy": (
            "analysis_code_commit_time_for_byte_determinism"
        ),
        "source_provenance": dict(bundle.source_provenance),
        "analysis_provenance": dict(bundle.analysis_provenance),
        "analysis_commit": bundle.analysis_provenance["analysis_commit"],
        "analysis_code_sha256": bundle.analysis_provenance[
            "analysis_code_sha256"
        ],
        "analysis_code_files": bundle.analysis_provenance[
            "analysis_code_files"
        ],
        "bootstrap": {
            "iterations": bundle.bootstrap_iterations,
            "seed": BOOTSTRAP_SEED,
            "unit": "target-fixed; paired replicate within target/truth/condition",
            "item_type_diagnostic_iterations": (
                ITEM_TYPE_DIAGNOSTIC_BOOTSTRAP_ITERATIONS
            ),
            "item_type_diagnostic_unit": (
                "target-fixed; paired-replicate resample; "
                "whole-journey event clusters"
            ),
        },
        "conditional_metric_audit": dict(bundle.conditional_metric_audit),
        "static_audit_policy": dict(bundle.static_audit_policy),
        "decisions": bundle.decisions,
        "hypothesis_evidence": bundle.hypothesis_evidence,
        "numeric_source": "metric_registry.json",
        "registry_metric_ids": sorted(registry_by_id),
        "validation": {
            **bundle.validation,
            "full_target_count": int(bundle.validation["target_count"]),
            "common_support_target_count_b9": bundle.no_repeat_sets[9].n_target,
            "common_support_target_count_b15": bundle.no_repeat_sets[15].n_target,
            "common_support_target_count_b25": bundle.no_repeat_sets[25].n_target,
        },
    }
    written.add(_write_json(root / "results.json", results))
    canonical_path = root / "canonical_views.csv"
    canonical_records = tuple(asdict(row) for row in bundle.canonical_rows)
    _write_csv(
        canonical_path,
        tuple(canonical_records[0]) if canonical_records else ("target",),
        canonical_records,
    )
    written.add(canonical_path)
    written.add(
        _write_json(
            root / "no_repeat_sets.json",
            {
                str(budget): {
                    "targets": list(value.targets),
                    "n_target": value.n_target,
                    "sha256": value.sha256,
                }
                for budget, value in sorted(bundle.no_repeat_sets.items())
            },
        )
    )
    written.add(
        _write_json(
            root / "h5_status.json",
            {
                "status": "PROGRAMMATIC_COMPLETE_H5_PENDING",
                "decision": None,
                "reason": "No validated S2 provider panel was supplied to S3.",
                "claim_generated": False,
            },
        )
    )
    hypotheses_path = root / "hypotheses.csv"
    _write_csv(
        hypotheses_path,
        ("hypothesis", "decision", "evidence_metric_ids"),
        (
            {
                "hypothesis": hypothesis,
                "decision": bundle.decisions[hypothesis],
                "evidence_metric_ids": "|".join(
                    bundle.hypothesis_evidence[hypothesis]
                ),
            }
            for hypothesis in ("H1", "H2", "H3", "H4", "H5")
        ),
    )
    written.add(hypotheses_path)
    fragment = _results_fragment(bundle, registry_by_id)
    fragment_path = root / "results_fragment.md"
    fragment_path.write_text(fragment, encoding="utf-8", newline="\n")
    written.add(fragment_path)

    for name, rows in sorted(bundle.table_rows.items()):
        csv_path = tables / f"{name}.csv"
        fieldnames = tuple(rows[0]) if rows else ("metric_id",)
        _write_csv(csv_path, fieldnames, rows)
        written.add(csv_path)

    for name, rows in sorted(bundle.figure_rows.items()):
        csv_path = figures / f"{name}.csv"
        fieldnames = tuple(rows[0]) if rows else ("metric_id",)
        _write_csv(csv_path, fieldnames, rows)
        written.add(csv_path)
        written.update(
            _write_publication_figure(
                name,
                rows,
                figures,
                generated_from=str(
                    bundle.analysis_provenance["analysis_code_committed_at_utc"]
                ),
            )
        )

    artifact_hashes = {
        str(path.relative_to(root)): hashlib.sha256(path.read_bytes()).hexdigest()
        for path in sorted(written, key=lambda value: str(value.relative_to(root)))
    }
    manifest = {
        "raw_hash": bundle.raw_hash,
        "source_run_started_at_utc": bundle.source_provenance[
            "run_started_at_utc"
        ],
        "analysis_code_committed_at_utc": bundle.analysis_provenance[
            "analysis_code_committed_at_utc"
        ],
        "analysis_timestamp_policy": (
            "analysis_code_commit_time_for_byte_determinism"
        ),
        "source_provenance": dict(bundle.source_provenance),
        "analysis_provenance": dict(bundle.analysis_provenance),
        "analysis_commit": bundle.analysis_provenance["analysis_commit"],
        "analysis_code_sha256": bundle.analysis_provenance[
            "analysis_code_sha256"
        ],
        "analysis_code_files": bundle.analysis_provenance[
            "analysis_code_files"
        ],
        "conditional_metric_audit": dict(bundle.conditional_metric_audit),
        "static_audit_policy": dict(bundle.static_audit_policy),
        "registry_metric_ids": sorted(registry_by_id),
        "files": {
            path: digest for path, digest in sorted(artifact_hashes.items())
        },
    }
    artifact_manifest_path = _write_json(root / "artifact_manifest.json", manifest)
    written.add(artifact_manifest_path)
    artifact_hashes["artifact_manifest.json"] = hashlib.sha256(
        artifact_manifest_path.read_bytes()
    ).hexdigest()
    contract_payload = _results_contract_payload(
        bundle,
        registry_by_id=registry_by_id,
        artifact_hashes=artifact_hashes,
    )
    contract_block_path = root / "results_contract_block.md"
    contract_block_path.write_text(
        _format_contract_block(contract_payload),
        encoding="utf-8",
        newline="\n",
    )
    return contract_block_path


def _mean_metric(
    metric_id: str,
    rows: Sequence[AnalysisRow],
    *,
    field: str,
    raw_hash: str,
) -> MetricValue:
    rows = tuple(row for row in rows if row.valid)
    if not rows:
        raise DatasetContractError(f"metric {metric_id} has no rows")
    grouped: dict[str, list[float]] = {}
    for row in rows:
        grouped.setdefault(row.target, []).append(float(getattr(row, field)))
    target_means = [sum(group) / len(group) for group in grouped.values()]
    numerator = sum(float(getattr(row, field)) for row in rows)
    return MetricValue(
        metric_id=metric_id,
        value=sum(target_means) / len(target_means),
        numerator=numerator,
        denominator=len(rows),
        weighting="equal_target_then_replicate",
        n_target=len(grouped),
        n_pair=len(rows),
        raw_hash=raw_hash,
    )


def _event_mean_metric(
    metric_id: str,
    events: Sequence[AnalysisEvent],
    *,
    value,
    distribution: Sequence[float],
    raw_hash: str,
) -> MetricValue:
    valid_events = tuple(event for event in events if event.valid)
    if not valid_events:
        raise DatasetContractError(f"metric {metric_id} has no valid events")
    grouped: dict[str, list[float]] = {}
    raw_values: list[float] = []
    for event in valid_events:
        event_value = float(value(event))
        if not math.isfinite(event_value):
            raise DatasetContractError(f"metric {metric_id} has a non-finite event")
        grouped.setdefault(event.target, []).append(event_value)
        raw_values.append(event_value)
    target_means = [sum(group) / len(group) for group in grouped.values()]
    journey_count = len(
        {
            (
                event.target,
                event.truth,
                event.condition,
                event.replicate,
                event.arm,
            )
            for event in valid_events
        }
    )
    low, high = percentile_interval(distribution)
    return MetricValue(
        metric_id=metric_id,
        value=sum(target_means) / len(target_means),
        numerator=sum(raw_values),
        denominator=len(raw_values),
        weighting=(
            "equal_target_then_event; misspecified_event_level; "
            "target_stratified_paired_replicate_resample; "
            "journey_cluster_preserved; bootstrap_iterations=10000; "
            "diagnostic_only_not_item_type_H1_H2_estimand"
        ),
        n_target=len(grouped),
        n_pair=journey_count,
        raw_hash=raw_hash,
        ci_low=low,
        ci_high=high,
    )


def _exclusion_reason_counts(
    rows: Sequence[AnalysisRow],
) -> dict[str, int]:
    counts: dict[str, int] = {}
    for row in rows:
        if row.budget != 25 or row.valid:
            continue
        reason = row.exclusion_reason or "unspecified_invalid_or_incomplete"
        counts[reason] = counts.get(reason, 0) + 1
    return {reason: counts[reason] for reason in sorted(counts)}


def _exclusion_arm_counts(rows: Sequence[AnalysisRow]) -> dict[str, int]:
    counts: dict[str, int] = {}
    for row in rows:
        if row.budget != 25 or row.valid:
            continue
        counts[row.arm] = counts.get(row.arm, 0) + 1
    return {arm: counts[arm] for arm in sorted(counts)}


def _predicate_rate_metric(
    metric_id: str,
    rows: Sequence[AnalysisRow],
    *,
    predicate,
    raw_hash: str,
) -> MetricValue:
    rows = tuple(row for row in rows if row.valid)
    if not rows:
        raise DatasetContractError(f"metric {metric_id} has no rows")
    grouped: dict[str, list[AnalysisRow]] = {}
    for row in rows:
        grouped.setdefault(row.target, []).append(row)
    target_rates = [
        sum(bool(predicate(row)) for row in target_rows) / len(target_rows)
        for target_rows in grouped.values()
    ]
    numerator = sum(bool(predicate(row)) for row in rows)
    return MetricValue(
        metric_id=metric_id,
        value=sum(target_rates) / len(target_rates),
        numerator=float(numerator),
        denominator=len(rows),
        weighting="equal_target_then_replicate",
        n_target=len(grouped),
        n_pair=len(rows),
        raw_hash=raw_hash,
    )


def _target_ratio_metric(
    metric_id: str,
    rows: Sequence[AnalysisRow],
    *,
    numerator,
    denominator,
    raw_hash: str,
    weighting: str,
    audit: dict[str, object] | None = None,
) -> MetricValue:
    declared_targets = tuple(sorted({row.target for row in rows}))
    rows = tuple(row for row in rows if row.valid)
    if not rows:
        raise DatasetContractError(f"metric {metric_id} has no rows")
    grouped: dict[str, list[AnalysisRow]] = {}
    for row in rows:
        grouped.setdefault(row.target, []).append(row)
    target_values: list[float] = []
    undefined_targets: list[str] = []
    for target in declared_targets:
        target_rows = grouped.get(target, [])
        target_denominator = sum(bool(denominator(row)) for row in target_rows)
        if target_denominator == 0:
            undefined_targets.append(target)
            continue
        target_numerator = sum(bool(numerator(row)) for row in target_rows)
        target_values.append(target_numerator / target_denominator)
    if not target_values:
        raise DatasetContractError(f"metric {metric_id} has an empty ratio denominator")
    raw_numerator = sum(bool(numerator(row)) for row in rows)
    raw_denominator = sum(bool(denominator(row)) for row in rows)
    if audit is not None:
        audit.update(
            {
                "point_declared_target_count": len(declared_targets),
                "point_defined_target_count": len(target_values),
                "point_undefined_target_count": len(undefined_targets),
                "point_undefined_target_ids": undefined_targets,
            }
        )
    return MetricValue(
        metric_id=metric_id,
        value=sum(target_values) / len(target_values),
        numerator=float(raw_numerator),
        denominator=raw_denominator,
        weighting=weighting,
        n_target=len(target_values),
        n_pair=raw_denominator,
        raw_hash=raw_hash,
    )


def _degradation_metric(
    metric_id: str,
    *,
    matched: MetricValue,
    misspecified: MetricValue,
    matched_distribution: Sequence[float],
    misspecified_distribution: Sequence[float],
    raw_hash: str,
) -> MetricValue:
    if (
        matched.denominator != misspecified.denominator
        or matched.n_target != misspecified.n_target
        or matched.n_pair != misspecified.n_pair
    ):
        raise DatasetContractError(
            f"degradation metric {metric_id} requires matched analysis grids"
        )
    if len(matched_distribution) != len(misspecified_distribution):
        raise DatasetContractError(
            f"degradation metric {metric_id} has mismatched bootstrap draws"
        )
    distribution = tuple(
        left - right
        for left, right in zip(
            matched_distribution,
            misspecified_distribution,
            strict=True,
        )
    )
    low, high = percentile_interval(distribution)
    return MetricValue(
        metric_id=metric_id,
        value=matched.value - misspecified.value,
        numerator=matched.numerator - misspecified.numerator,
        denominator=matched.denominator,
        weighting=(
            "equal_target_then_paired_replicate; "
            "matched_minus_misspecified_condition_contrast"
        ),
        n_target=matched.n_target,
        n_pair=matched.n_pair,
        raw_hash=raw_hash,
        ci_low=low,
        ci_high=high,
    )


def _validate_source_provenance(
    source_provenance: Mapping[str, str],
) -> dict[str, str]:
    required = (
        "run_id",
        "run_started_at_utc",
        "runner_commit",
        "experiment_tag",
        "config_sha256",
        "source_manifest_sha256",
        "analysis_plan_commit",
        "analysis_plan_sha256",
    )
    missing = [
        key
        for key in required
        if not isinstance(source_provenance.get(key), str)
        or not source_provenance[key]
    ]
    if missing:
        raise DatasetContractError(
            "analysis source provenance is incomplete: " + ", ".join(missing)
        )
    if not source_provenance["run_started_at_utc"].endswith("Z"):
        raise DatasetContractError("run_started_at_utc must be an explicit UTC timestamp")
    return {key: source_provenance[key] for key in required}


