    axes[1].legend(frameon=False, loc="best")
    n_pair = min(int(row["n_pair"]) for row in rows)
    figure.suptitle(title)
    _add_figure_footer(
        figure,
        f"Points are target-equal estimates; error bars: 95% CI; "
        f"n = {n_pair:,} journeys per arm-budget cell.",
    )
    return figure


