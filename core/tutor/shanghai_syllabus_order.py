def get_ordered_nodes(all_nodes: list) -> list:
    """
    根据上海考纲顺序排序知识点。

    Args:
        all_nodes: 所有知识点列表

    Returns:
        排序后的知识点列表
    """
    # 先按考纲顺序排序已有的
    ordered = [n for n in SHANGHAI_SYLLABUS_ORDER if n in all_nodes]
    # 剩余的按字母顺序排在后面
    rest = sorted([n for n in all_nodes if n not in SHANGHAI_SYLLABUS_ORDER])
    return ordered + rest
